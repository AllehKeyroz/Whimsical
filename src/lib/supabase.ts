import { createClient, type SupabaseClient, type User } from "@supabase/supabase-js";
import type { Board, Folder } from "../types";

export interface SupabaseConfig {
  url: string;
  key: string;
}

interface RuntimeEnv {
  VITE_SUPABASE_URL?: string;
  VITE_SUPABASE_ANON_KEY?: string;
}

export interface CloudBoardRow {
  id: string;
  owner_id: string;
  title: string;
  folder_id: string | null;
  document: Board;
  is_public?: boolean;
  share_token?: string | null;
  created_at: string;
  updated_at: string;
}

export interface CloudFolderRow {
  id: string;
  owner_id: string;
  name: string;
  created_at: string;
  updated_at?: string;
}

function runtimeEnv(): RuntimeEnv {
  if (typeof window === "undefined") return {};
  return window.__WHIM_ENV__ ?? {};
}

function envUrl(): string {
  return (runtimeEnv().VITE_SUPABASE_URL || import.meta.env.VITE_SUPABASE_URL || "").trim();
}
function envKey(): string {
  return (runtimeEnv().VITE_SUPABASE_ANON_KEY || import.meta.env.VITE_SUPABASE_ANON_KEY || "").trim();
}

function cleanUrl(url: string): string {
  return url.trim().replace(/\/+$/, "");
}

/**
 * Credentials come only from the environment:
 * - `window.__WHIM_ENV__` generated by the container entrypoint from `.env`
 *   (Easypanel/Docker environment variables), or
 * - `import.meta.env.VITE_*` baked in at build time.
 */
export function getSupabaseConfig(): SupabaseConfig {
  return { url: cleanUrl(envUrl()), key: envKey() };
}

export function isSupabaseConfigured(): boolean {
  const cfg = getSupabaseConfig();
  return !!cfg.url && !!cfg.key;
}

let client: SupabaseClient | null = null;

export function getSupabase(): SupabaseClient | null {
  if (client) return client;
  const cfg = getSupabaseConfig();
  if (!cfg.url || !cfg.key) return null;
  try {
    client = createClient(cfg.url, cfg.key, {
      auth: {
        persistSession: true,
        autoRefreshToken: true,
        detectSessionInUrl: true,
        storageKey: "kdsflux.supabase.auth",
      },
    });
  } catch {
    client = null;
  }
  return client;
}

export async function getCloudSession(): Promise<{ user: User | null; error: string | null }> {
  const supabase = getSupabase();
  if (!supabase) return { user: null, error: "Supabase não configurado." };
  try {
    const { data, error } = await supabase.auth.getSession();
    if (error) return { user: null, error: error.message };
    return { user: data.session?.user ?? null, error: null };
  } catch (error) {
    return { user: null, error: error instanceof Error ? error.message : "Falha ao ler a sessão." };
  }
}

export function onCloudAuthChange(callback: (user: User | null) => void): () => void {
  const supabase = getSupabase();
  if (!supabase) return () => undefined;
  const { data } = supabase.auth.onAuthStateChange((_event, session) => {
    callback(session?.user ?? null);
  });
  return () => data.subscription.unsubscribe();
}

export async function cloudSignIn(email: string, password: string): Promise<{ user: User | null; error: string | null }> {
  const supabase = getSupabase();
  if (!supabase) return { user: null, error: "Supabase não configurado." };
  const { data, error } = await supabase.auth.signInWithPassword({ email: email.trim(), password });
  return { user: data.user ?? null, error: error?.message ?? null };
}

export interface CloudProfile {
  id: string;
  display_name: string | null;
  organization_name: string | null;
}

export async function cloudSignUp(
  email: string,
  password: string,
  displayName: string,
  organization: string,
): Promise<{ user: User | null; needsConfirmation: boolean; error: string | null }> {
  const supabase = getSupabase();
  if (!supabase) return { user: null, needsConfirmation: false, error: "Supabase não configurado." };
  const { data, error } = await supabase.auth.signUp({
    email: email.trim(),
    password,
    options: {
      data: {
        display_name: displayName.trim() || email.split("@")[0],
        organization_name: organization.trim().slice(0, 60),
      },
      emailRedirectTo: window.location.origin,
    },
  });
  return {
    user: data.user ?? null,
    needsConfirmation: !data.session,
    error: error?.message ?? null,
  };
}

export async function cloudSignOut(): Promise<string | null> {
  const supabase = getSupabase();
  if (!supabase) return null;
  const { error } = await supabase.auth.signOut();
  return error?.message ?? null;
}

export async function cloudChangePassword(password: string): Promise<string | null> {
  const supabase = getSupabase();
  if (!supabase) return "Supabase não configurado.";
  const { error } = await supabase.auth.updateUser({ password });
  return error?.message ?? null;
}

export async function cloudGetProfile(
  userId: string,
): Promise<{ profile: CloudProfile | null; error: string | null }> {
  const supabase = getSupabase();
  if (!supabase) return { profile: null, error: "Supabase não configurado." };
  const { data, error } = await supabase
    .from("profiles")
    .select("id, display_name, organization_name")
    .eq("id", userId)
    .maybeSingle();
  if (error) return { profile: null, error: error.message };
  return { profile: (data as CloudProfile | null) ?? null, error: null };
}

export async function cloudUpdateProfile(
  userId: string,
  displayName: string,
  organization: string,
): Promise<string | null> {
  const supabase = getSupabase();
  if (!supabase) return "Supabase não configurado.";
  const { error } = await supabase.from("profiles").upsert(
    {
      id: userId,
      display_name: displayName.trim().slice(0, 80),
      organization_name: organization.trim().slice(0, 60),
      updated_at: new Date().toISOString(),
    },
    { onConflict: "id" },
  );
  return error?.message ?? null;
}

export interface ApiTokenRow {
  id: string;
  name: string;
  prefix: string;
  created_at: string;
  last_used_at: string | null;
  revoked_at: string | null;
}

export async function cloudListApiTokens(
  userId: string,
): Promise<{ rows: ApiTokenRow[]; error: string | null }> {
  const supabase = getSupabase();
  if (!supabase) return { rows: [], error: "Supabase não configurado." };
  const { data, error } = await supabase
    .from("api_tokens")
    .select("id,name,prefix,created_at,last_used_at,revoked_at")
    .eq("owner_id", userId)
    .order("created_at", { ascending: false });
  if (error) return { rows: [], error: error.message };
  return { rows: (data ?? []) as ApiTokenRow[], error: null };
}

export async function cloudCreateApiToken(
  userId: string,
  name: string,
  tokenHash: string,
  prefix: string,
): Promise<string | null> {
  const supabase = getSupabase();
  if (!supabase) return "Supabase não configurado.";
  const { error } = await supabase.from("api_tokens").insert({
    owner_id: userId,
    name: name.trim().slice(0, 80) || "MCP token",
    token_hash: tokenHash,
    prefix,
  });
  return error?.message ?? null;
}

export async function cloudRevokeApiToken(id: string): Promise<string | null> {
  const supabase = getSupabase();
  if (!supabase) return "Supabase não configurado.";
  const { error } = await supabase.from("api_tokens").update({ revoked_at: new Date().toISOString() }).eq("id", id);
  return error?.message ?? null;
}

export interface BoardChangePayload {
  eventType: "INSERT" | "UPDATE" | "DELETE";
  new: Record<string, unknown>;
  old: Record<string, unknown>;
}

export function subscribeToBoardChanges(
  userId: string,
  onChange: (payload: BoardChangePayload) => void,
): () => void {
  const supabase = getSupabase();
  if (!supabase) return () => undefined;
  const channel = supabase
    .channel(`kdsflux-boards-${userId}`)
    .on(
      "postgres_changes",
      { event: "*", schema: "public", table: "boards", filter: `owner_id=eq.${userId}` },
      (payload) => onChange(payload as unknown as BoardChangePayload),
    )
    .subscribe();
  return () => {
    void supabase.removeChannel(channel);
  };
}

export async function cloudListBoards(
  userId: string,
): Promise<{ rows: CloudBoardRow[]; error: string | null }> {
  const supabase = getSupabase();
  if (!supabase) return { rows: [], error: "Supabase não configurado." };
  const { data, error } = await supabase
    .from("boards")
    .select("*")
    .eq("owner_id", userId)
    .order("updated_at", { ascending: false });
  if (error) return { rows: [], error: error.message };
  return { rows: (data ?? []) as CloudBoardRow[], error: null };
}

export async function cloudUpsertBoard(board: Board, userId: string): Promise<string | null> {
  const supabase = getSupabase();
  if (!supabase) return "Supabase não configurado.";
  const { error } = await supabase.from("boards").upsert(
    {
      id: board.id,
      owner_id: userId,
      title: board.title,
      folder_id: board.folderId ?? null,
      document: board,
      updated_at: new Date(board.updatedAt).toISOString(),
    },
    { onConflict: "id" },
  );
  return error?.message ?? null;
}

export async function cloudDeleteBoard(id: string): Promise<string | null> {
  const supabase = getSupabase();
  if (!supabase) return "Supabase não configurado.";
  const { error } = await supabase.from("boards").delete().eq("id", id);
  return error?.message ?? null;
}

export async function cloudListFolders(userId: string): Promise<{ rows: CloudFolderRow[]; error: string | null }> {
  const supabase = getSupabase();
  if (!supabase) return { rows: [], error: "Supabase não configurado." };
  const { data, error } = await supabase.from("folders").select("*").eq("owner_id", userId).order("created_at");
  if (error) return { rows: [], error: error.message };
  return { rows: (data ?? []) as CloudFolderRow[], error: null };
}

export async function cloudReplaceFolders(folders: Folder[], userId: string): Promise<string | null> {
  const supabase = getSupabase();
  if (!supabase) return "Supabase não configurado.";
  if (!folders.length) return null;
  const { error } = await supabase.from("folders").upsert(
    folders.map((f) => ({
      id: f.id,
      owner_id: userId,
      name: f.name,
      created_at: new Date(f.createdAt).toISOString(),
    })),
    { onConflict: "id" },
  );
  // Intentionally only upserts: deleting a folder is an explicit user action,
  // not a side effect of syncing a device that hasn't seen the folder yet.
  return error?.message ?? null;
}
